export type IconName = keyof typeof ART

export function Icon({ name, size = 14, color = 'currentColor' }: { name: IconName; size?: number; color?: string }) {
  return (
    <svg className="px-icon" width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden>
      {ART[name].flatMap((row, y) => [...row].map((c, x) => (c === '#' ? <rect key={`${x},${y}`} x={x} y={y} width="1" height="1" fill={color} /> : null)))}
    </svg>
  )
}

// Same art as a data URL, for deck.gl sprites on the map.
export function iconUrl(name: IconName, color: string) {
  const rects = ART[name].flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `<rect x='${x}' y='${y}' width='1' height='1' fill='${color}'/>` : ''))).join('')
  return `data:image/svg+xml;utf8,${encodeURIComponent(`<svg xmlns='http://www.w3.org/2000/svg' width='64' height='64' viewBox='0 0 8 8' shape-rendering='crispEdges'>${rects}</svg>`)}`
}
